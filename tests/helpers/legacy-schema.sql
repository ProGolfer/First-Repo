-- Copy of the PRODUCTION schema (as of 2026-11-18) for the tables Phase 2 touches, including the open policies
-- and grants. Used to prove the new migrations change nothing that exists today.
create table public.league_players (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  normalized_name text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.game_history (
  id bigint generated by default as identity primary key,
  league_player_id uuid references public.league_players(id) on delete set null,
  player_id uuid, player_name text not null, name text, game_date date not null, date date, season text,
  team_id bigint, team_name text, place integer, finish integer, position integer,
  won boolean not null default false, is_winner boolean not null default false, result text,
  is_captain boolean not null default false, was_captain boolean not null default false, captain boolean not null default false,
  captain_win integer not null default 0, round_score numeric, stroke_score numeric, points numeric, total_points numeric,
  front_score numeric, back_score numeric, total_score numeric, team_total numeric,
  money_won numeric not null default 0, winnings numeric not null default 0, payout numeric not null default 0,
  front_win integer not null default 0, back_win integer not null default 0, total_win integer not null default 0,
  birdies integer not null default 0, finalized_by text, finalized_at timestamptz, created_at timestamptz not null default now()
);
create unique index game_history_player_date_unique on public.game_history (league_player_id, game_date) where league_player_id is not null;
create table public.players (
  id uuid primary key default gen_random_uuid(), name text not null, phone text,
  status text not null default 'pending' check (status in ('pending','approved','declined')),
  team integer, course text default 'Cliffside Golf Club', registered_at timestamptz not null default now(),
  is_captain boolean not null default false, device_token text, score numeric,
  league_player_id uuid references public.league_players(id) on delete set null, auth_user_id uuid
);
create table public.player_profiles (
  id uuid primary key default gen_random_uuid(),
  player_id uuid not null unique references public.players(id) on delete cascade,
  profile_photo_path text, cover_photo_path text, nickname text, hometown text, favorite_course text,
  favorite_club text, favorite_memory text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
alter table public.league_players enable row level security;
alter table public.players enable row level security;
alter table public.player_profiles enable row level security;
create policy "Public can read league players" on public.league_players for select using (true);
create policy "Public can add league players" on public.league_players for insert with check (true);
create policy "Public can update league players" on public.league_players for update using (true) with check (true);
create policy "open players" on public.players for all using (true) with check (true);
create policy "Profiles are publicly readable" on public.player_profiles for select using (true);
create policy "Profiles can be created" on public.player_profiles for insert with check (true);
create policy "Profiles can be updated" on public.player_profiles for update using (true) with check (true);
